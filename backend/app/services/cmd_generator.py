from pathlib import Path


BASE_DIR = Path(__file__).resolve().parent.parent.parent


class CommandGenerator:

    def __init__(
        self,
        output_dir=None
    ):

        self.output_dir = (
            Path(output_dir)
            if output_dir
            else BASE_DIR / "generated"
        )

        self.output_dir.mkdir(
            parents=True,
            exist_ok=True
        )

    def sanitize_value(
        self,
        value: str
    ) -> str:

        if value is None:
            return ""

        return (
            str(value)
            .replace("\r", " ")
            .replace("\n", " ")
            .replace("|", "-")
            .strip()
        )

    def generate(
        self,
        job_id: int,
        assets: list
    ) -> str:

        filename = f"print_job_{job_id}.cmd"

        file_path = (
            self.output_dir / filename
        )

        lines = [
            f"REM RFID PRINT JOB {job_id}",
            "REM Generated by RFID PRINTING",
            ""
        ]

        for asset in assets:

            bien_id = self.sanitize_value(
                asset.bien_id
            )

            designation = self.sanitize_value(
                asset.bien_designation
            )

            lines.append(
                f"PRINT|bien_id={bien_id}"
                f"|designation={designation}"
            )

        file_path.write_text(
            "\n".join(lines),
            encoding="utf-8"
        )

        return filename